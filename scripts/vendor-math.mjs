import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const root = join(import.meta.dirname, '..');
const upstream = dirname(require.resolve('katex/package.json'));
const { version } = JSON.parse(
  await readFile(join(upstream, 'package.json'), 'utf8'),
);
const license = await readFile(join(upstream, 'LICENSE'), 'utf8');
let css = await readFile(join(upstream, 'dist/katex.min.css'), 'utf8');
const fonts = [...css.matchAll(/src:url\(fonts\/([^)]*\.woff2)\)[^;}]+;?/g)];
if (fonts.length !== 20) throw new Error('KaTeX font manifest changed.');
for (const [declaration, name] of fonts) {
  const data = await readFile(join(upstream, 'dist/fonts', name));
  css = css.replace(
    declaration,
    `src:url(data:font/woff2;base64,${data.toString('base64')}) format("woff2");`,
  );
}
if (/url\((?!data:)/.test(css))
  throw new Error('KaTeX CSS still references an external asset.');
if ([...css.matchAll(/@font-face\{/g)].length !== 20)
  throw new Error('KaTeX embedded font declarations are incomplete.');
// One local copy serves both the extension and a script-free single-file export.
css = `/* KaTeX ${version} — ${license.replaceAll('*/', '* /')} */\n` + css;
const layout = await readFile(join(root, 'src/lib/math.css'), 'utf8');
await writeFile(
  join(root, 'src/lib/math-style-data.ts'),
  `// Generated by scripts/vendor-math.mjs from katex ${version}.\n` +
    `export const MATH_FONT_CSS = ${JSON.stringify(css)};\n` +
    `export const MATH_LAYOUT_CSS = ${JSON.stringify(layout)};\n`,
);
await mkdir(join(root, 'public/licenses'), { recursive: true });
await writeFile(join(root, 'public/licenses/KaTeX-MIT.txt'), license);
console.log(`Local KaTeX ${version} CSS and WOFF2 fonts prepared.`);
